"""Whether a file is machine-written, so rewording it by hand is wrong.

A generated file is rewritten by the next regeneration, and a hand edit to a
checked-in snapshot usually fails the repository's own drift check. The pull
request therefore names such a file once, as generated, instead of listing its
comments as sentences to reword.

Two signs count: a marker in the first lines of the file, and the
``linguist-generated`` attribute in ``.gitattributes``.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

#: How many leading lines are searched for the marker.
_HEADER_LINES = 12
#: A whole-file assertion, never a bare phrase: prose such as "tokens generated
#: by the auth service" or "do not edit this list without asking" is not one.
_MARKER = re.compile(
    r"(?:this|the) file (?:is|was) (?:auto-?)?generated|@generated|code generated .* do not edit|<auto-generated",
    re.IGNORECASE,
)


def has_marker(source: str) -> bool:
    """Whether the first lines of ``source`` say the file is generated."""
    return _MARKER.search("\n".join(source.split("\n", _HEADER_LINES)[:_HEADER_LINES])) is not None


def marked_generated(path: str) -> bool:
    """Whether ``git`` is told the file is generated (``linguist-generated``)."""
    target = Path(path)
    try:
        out = subprocess.run(
            ["git", "check-attr", "linguist-generated", "--", target.name],
            cwd=target.resolve().parent,
            capture_output=True,
            text=True,
            timeout=10,
            check=True,
        ).stdout
    except (OSError, subprocess.SubprocessError):
        return False
    value = out.rsplit(":", 1)[-1].strip()
    return value not in ("", "unspecified", "unset") and value != "false"


def is_generated(path: str, source: str) -> bool:
    return has_marker(source) or marked_generated(path)
